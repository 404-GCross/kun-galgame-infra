// w140_test.go — the W1-pre bridge-nativization mirror steps (refs/proj/140,
// refs/plans/10-data-layer-retirement/02-w1pre-bridge-nativization.md).
//
// Every step is exercised the same way, because a mirror has four properties a
// fill-missing step does not and all four are load-bearing:
//
//	① the materialized rows carry the BRIDGE's values, column by column;
//	② the set-diff runs all three ways — insert a new row, UPDATE a stale one,
//	   DELETE one the wiki side no longer justifies;
//	③ rows OUTSIDE the ownership scope are not read, not updated, not deleted;
//	④ a second pass decides nothing (Insert=Update=Delete=0), which is what makes
//	   the step safe as a daily follow-up.
//
// TestMain / the pool wiring live in w2_test.go.

// mirror140GalgameIDs are the wiki body ids these tests own. Cleanup is a targeted
// DELETE, never a TRUNCATE: the galgame tables are shared with other suites.
var mirror140GalgameIDs = []int64{7401, 7402, 7403}

// mirror140TagIDs are the wiki tag vocabulary ids these tests own (names are
// 140-suffixed so the real table's UNIQUE(name) can never collide).
var mirror140TagIDs = []int64{74001, 74002, 74003}

// ensureMirrorStubs provisions every wiki table the p..t steps read. CREATE …
// IF NOT EXISTS is a no-op against the real schema, and the INSERT helpers always
// pass the real schema's defaultless NOT NULL columns.
func ensureMirrorStubs(t *testing.T) {
	t.Helper()
	ensureGalgameMediaStubs(t) // galgame (+ the intro columns) and the two media tables
	for _, col := range []string{"name_ja_jp", "name_en_us", "name_zh_cn", "name_zh_tw"} {
		require.NoError(t, testDB.Exec(
			`ALTER TABLE galgame ADD COLUMN IF NOT EXISTS `+col+` text NOT NULL DEFAULT ''`).Error)
	}
	// content_limit is the editorial display axis step q's second arm mirrors
	// (refs/proj/140 §5b); size/default copied from the wiki model.
	require.NoError(t, testDB.Exec(
		`ALTER TABLE galgame ADD COLUMN IF NOT EXISTS content_limit varchar(10) DEFAULT 'sfw'`).Error)
	for _, stmt := range []string{
		`CREATE TABLE IF NOT EXISTS galgame_alias (
			id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
			galgame_id bigint NOT NULL,
			name text NOT NULL DEFAULT '')`,
		`CREATE TABLE IF NOT EXISTS galgame_tag (
			id bigint PRIMARY KEY, name text NOT NULL UNIQUE,
			category text NOT NULL, description text DEFAULT '')`,
		`CREATE TABLE IF NOT EXISTS galgame_tag_relation (
			galgame_id bigint NOT NULL, tag_id bigint NOT NULL,
			spoiler_level bigint DEFAULT 0, source varchar(16) DEFAULT '',
			PRIMARY KEY (galgame_id, tag_id))`,
		`CREATE TABLE IF NOT EXISTS galgame_vndb_meta (
			galgame_id bigint PRIMARY KEY, vndb_id text NOT NULL, rating numeric,
			vote_count bigint NOT NULL, synced_at timestamptz NOT NULL)`,
		`CREATE TABLE IF NOT EXISTS galgame_bangumi_meta (
			galgame_id bigint PRIMARY KEY, bid bigint NOT NULL, score numeric NOT NULL,
			rank bigint NOT NULL, total bigint NOT NULL, nsfw boolean NOT NULL,
			synced_at timestamptz NOT NULL)`,
		`CREATE TABLE IF NOT EXISTS galgame_eg_meta (
			galgame_id bigint PRIMARY KEY, eg_game_id bigint NOT NULL, median bigint,
			vote_count bigint NOT NULL, synced_at timestamptz NOT NULL)`,
		`CREATE TABLE IF NOT EXISTS galgame_dlsite_meta (
			galgame_id bigint PRIMARY KEY, workno text NOT NULL, rate_average_star numeric,
			rate_count bigint, dl_count bigint, wishlist_count bigint, review_count bigint,
			synced_at timestamptz NOT NULL)`,
	} {
		require.NoError(t, testDB.Exec(stmt).Error)
	}
}

// resetMirror clears this suite's wiki rows and the catalog facet tables the
// mirror steps own, so each test starts from a known state.
func resetMirror(t *testing.T) {
	t.Helper()
	ensureMirrorStubs(t)
	require.NoError(t, testDB.Exec(`DELETE FROM galgame_tag_relation WHERE galgame_id IN ?`, mirror140GalgameIDs).Error)
	require.NoError(t, testDB.Exec(`DELETE FROM galgame_tag WHERE id IN ?`, mirror140TagIDs).Error)
	require.NoError(t, testDB.Exec(`DELETE FROM galgame_alias WHERE galgame_id IN ?`, mirror140GalgameIDs).Error)
	for _, tbl := range []string{"galgame_vndb_meta", "galgame_bangumi_meta", "galgame_eg_meta", "galgame_dlsite_meta"} {
		require.NoError(t, testDB.Exec(`DELETE FROM `+tbl+` WHERE galgame_id IN ?`, mirror140GalgameIDs).Error)
	}
	require.NoError(t, testDB.Exec(`DELETE FROM galgame WHERE id IN ?`, mirror140GalgameIDs).Error)
	for _, tbl := range []string{
		"catalog_work_title", "catalog_work_intro", "catalog_work_tag",
		"catalog_work_rating", "catalog_work_popularity", "catalog_external_ref",
		"catalog_tag_source_map", "catalog_tag", "catalog_work",
	} {
		require.NoError(t, testDB.Exec("TRUNCATE "+tbl+" CASCADE").Error)
	}
}

// mkClaimedWork creates a work CLAIMED by the given wiki body — the population
// every mirror step runs over (site + product_work_id, the read face's own
// partition key).
func mkClaimedWork(t *testing.T, galgameID int64, name string) int64 {
	t.Helper()
	site := siteGalgameWiki
	w := model.CatalogWork{
		MediumID: mediumGalgame, OLang: "ja", DisplayName: name,
		Site: &site, ProductWorkID: &galgameID,
	}
	require.NoError(t, testDB.Create(&w).Error)
	return w.ID
}

