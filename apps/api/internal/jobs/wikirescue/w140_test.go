// TestDisplayNSFWMirror pins step q's SECOND arm — the A2-R5 editorial display
// axis nativized onto catalog_work.display_nsfw (refs/proj/140 §5b).
//
// The four cases are the whole projection: the wiki 'nsfw' spelling is the ONLY
// true, every other value (including a body that is simply gone) is false, both
// directions are corrected so the column converges, and a BODYLESS work's column
// is outside the scope — it is never read by the display projection and must not
// be written by this step. The bodies carry no intro text, so the step's Touched
// counts display flips alone.
func TestDisplayNSFWMirror(t *testing.T) {
	resetMirror(t)
	ctx := context.Background()

	mkBody(t, 7401, "", "", "", "", "", "", "")
	mkBody(t, 7402, "", "", "", "", "", "", "")
	mkBody(t, 7403, "", "", "", "", "", "", "")
	setBodyLimit(t, 7401, "nsfw")
	setBodyLimit(t, 7402, "sfw")
	setBodyLimit(t, 7403, "nsfw")

	promote := mkClaimedWork(t, 7401, "wiki says nsfw")
	stays := mkClaimedWork(t, 7402, "wiki says sfw")
	already := mkClaimedWork(t, 7403, "already flagged")
	// A claim whose wiki body is GONE declares nothing → false, so a stale true
	// has to come back down.
	demote := mkClaimedWork(t, 7499, "body vanished")
	bodyless := mkWork(t, "no claim at all")
	require.NoError(t, testDB.Exec(
		`UPDATE catalog_work SET display_nsfw = true WHERE id IN ?`,
		[]int64{already, demote, bodyless}).Error)

	dry, err := newRunner(t, false).runStep(ctx, "q")
	require.NoError(t, err)
	assert.Equal(t, 2, dry.Scalar, "one promotion and one demotion decided")
	assert.Equal(t, 2, dry.Touched, "the forecast marks exactly the flipping works")
	assert.False(t, displayNSFW(t, promote), "a dry run writes nothing")
	assert.True(t, displayNSFW(t, demote), "a dry run writes nothing")

	st, err := newRunner(t, true).runStep(ctx, "q")
	require.NoError(t, err)
	assert.Equal(t, 2, st.Scalar)
	assert.True(t, displayNSFW(t, promote), "wiki 'nsfw' → true")
	assert.False(t, displayNSFW(t, stays), "wiki 'sfw' → false")
	assert.True(t, displayNSFW(t, already), "left alone, already correct")
	assert.False(t, displayNSFW(t, demote), "no body declares nothing → false")
	assert.True(t, displayNSFW(t, bodyless), "a bodyless work's column is outside the scope")

	second, err := newRunner(t, true).runStep(ctx, "q")
	require.NoError(t, err)
	assert.Zero(t, second.Scalar, "converged")
	assert.Zero(t, second.Touched, "and touches nothing")
}

// TestTagVocabularySexualIgnoresNonExactAndForeignAnchors pins the anchor
// discipline of step r's vocabulary arm — the assertion that moved here from the
// read face (service.TestTagSexualIgnoresNonExactAndForeignAnchors) when the
// derivation itself did.
//
// Only the EXACT galgame_wiki tag anchor may set catalog_tag.sexual. A probable
// anchor is an unreviewed hypothesis, and another source's anchor is a different
// key space that happens to spell the same digits — neither may flip a safety flag.
func TestTagVocabularySexualIgnoresNonExactAndForeignAnchors(t *testing.T) {
	resetMirror(t)
	ctx := context.Background()

	mkTag(t, 74002, "エロ-140", "sexual")
	wikiSrc, vndbSrc := sourceID(t, "galgame_wiki"), sourceID(t, "vndb")

	probable := model.CatalogTag{Name: "probable-140", Tier: 0, Kind: 0}
	require.NoError(t, testDB.Create(&probable).Error)
	foreign := model.CatalogTag{Name: "foreign-140", Tier: 0, Kind: 0}
	require.NoError(t, testDB.Create(&foreign).Error)
	require.NoError(t, testDB.Create(&model.CatalogExternalRef{
		EntityType: model.EntityTypeTag, EntityID: probable.ID, SourceID: wikiSrc,
		ExternalID: "74002", LinkKind: model.LinkKindProbable}).Error)
	require.NoError(t, testDB.Create(&model.CatalogExternalRef{
		EntityType: model.EntityTypeTag, EntityID: foreign.ID, SourceID: vndbSrc,
		ExternalID: "74002", LinkKind: model.LinkKindExact}).Error)

	st, err := newRunner(t, true).runStep(ctx, "r")
	require.NoError(t, err)
	assert.Zero(t, st.Vocab, "neither anchor justifies a flag")
	for _, tc := range []struct {
		id   int64
		name string
	}{{probable.ID, "a PROBABLE anchor"}, {foreign.ID, "another source's anchor"}} {
		var sexual bool
		require.NoError(t, testDB.Raw(`SELECT sexual FROM catalog_tag WHERE id = ?`, tc.id).Scan(&sexual).Error)
		assert.False(t, sexual, "%s must not flip the sexual flag", tc.name)
	}
}
