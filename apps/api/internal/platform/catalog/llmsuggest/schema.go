// The src_llm schema is tool-owned rebuildable staging (srcbangumi discipline):
// CREATE SCHEMA + AutoMigrate at startup, entirely outside migrate-catalog's
// Gold order. Every suggestion row is keyed by (task/input_hash/model/
// prompt_version) so a re-run resumes instead of re-querying the model.

// Prompt versions — bump on any prompt change so a re-run re-judges rather than
// resuming stale answers. Single-item and batch prompts are versioned apart.
const (
	PromptNamePairV1   = "name-pair-v1"
	PromptNamePairV1B  = "name-pair-v1-batch"
	PromptResidueV1    = "residue-v1"
	PromptBidVerdictV1 = "bid-verdict-v1"
)

// Verdict values (also the model's guided-JSON enum).
const (
	VerdictSame      = "same"
	VerdictDifferent = "different"
	VerdictUnsure    = "unsure"
)

// Run records one pipeline execution: task, model, prompt version, per-run
// counts and timing — the audit trail of the suggestion batches.
type Run struct {
	ID            int64          `gorm:"primaryKey;autoIncrement:false;type:bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY;default:(-)" json:"id"`
	Task          string         `gorm:"not null" json:"task"`
	Model         string         `gorm:"not null" json:"model"`
	PromptVersion string         `gorm:"not null" json:"prompt_version"`
	Counts        datatypes.JSON `gorm:"type:jsonb" json:"counts"`
	Notes         string         `gorm:"not null;default:''" json:"notes"`
	StartedAt     time.Time      `gorm:"not null" json:"started_at"`
}

func (Run) TableName() string { return "src_llm.run" }

// NamePairJudgment is one "are A and B the same creator's names?" judgment.
// Used by the gold-set calibration (gold_label + source_rule set) and reusable
// for future name-alignment tasks. verdict/reason empty + error set = a call
// that failed after retries (recorded, never crashes the batch). confidence is
// archived for sorting ONLY (doc 17 §4 — never thresholded into an action).
type NamePairJudgment struct {
	ID            int64   `gorm:"primaryKey;autoIncrement:false;type:bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY;default:(-)" json:"id"`
	Task          string  `gorm:"not null;uniqueIndex:uq_name_pair,priority:1" json:"task"`
	InputHash     string  `gorm:"not null;uniqueIndex:uq_name_pair,priority:2" json:"input_hash"`
	Model         string  `gorm:"not null;uniqueIndex:uq_name_pair,priority:3" json:"model"`
	PromptVersion string  `gorm:"not null;uniqueIndex:uq_name_pair,priority:4" json:"prompt_version"`
	A             string  `gorm:"not null" json:"a"`
	B             string  `gorm:"not null" json:"b"`
	GoldLabel     string  `gorm:"not null;default:''" json:"gold_label"`
	SourceRule    string  `gorm:"not null;default:''" json:"source_rule"`
	Verdict       string  `gorm:"not null;default:''" json:"verdict"`
	Reason        string  `gorm:"not null;default:''" json:"reason"`
	Confidence    float64 `gorm:"not null;default:0" json:"confidence"`
	Error         string  `gorm:"not null;default:''" json:"error"`
	CreatedAt     time.Time
}

func (NamePairJudgment) TableName() string { return "src_llm.name_pair_judgment" }

// InfoboxExtraction is a SUGGESTED field extraction for one parse_error residue
