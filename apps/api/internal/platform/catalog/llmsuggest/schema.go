func (InfoboxExtraction) TableName() string { return "src_llm.infobox_extraction" }

// BidIdentityVerdict is one bid-exact pair audited (step 11 carry-over): does
// the wiki galgame's name set and the Bangumi subject's name set refer to the
// same work? layer is the deterministic pre-classification (pass/boundary/
// suspect); verdict/reason are the LLM adjudication for boundary+suspect only
// (pass rows carry no LLM call). Detection only — zero ref re-grading.
type BidIdentityVerdict struct {
	ID            int64   `gorm:"primaryKey;autoIncrement:false;type:bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY;default:(-)" json:"id"`
	WorkID        int64   `gorm:"not null" json:"work_id"`
	GalgameID     int64   `gorm:"not null" json:"galgame_id"`
	BID           int64   `gorm:"column:bid;not null" json:"bid"`
	Layer         string  `gorm:"not null" json:"layer"`
	WikiNames     string  `gorm:"not null;default:''" json:"wiki_names"`
	SubjectNames  string  `gorm:"not null;default:''" json:"subject_names"`
	InputHash     string  `gorm:"not null;uniqueIndex:uq_bid_verdict,priority:1" json:"input_hash"`
	Model         string  `gorm:"not null;uniqueIndex:uq_bid_verdict,priority:2" json:"model"`
	PromptVersion string  `gorm:"not null;uniqueIndex:uq_bid_verdict,priority:3" json:"prompt_version"`
	Verdict       string  `gorm:"not null;default:''" json:"verdict"`
	Reason        string  `gorm:"not null;default:''" json:"reason"`
	Confidence    float64 `gorm:"not null;default:0" json:"confidence"`
	Error         string  `gorm:"not null;default:''" json:"error"`
	CreatedAt     time.Time
	// Human-review resolution (step 20 B-track worklist). The deterministic +
	// LLM layers only DETECT; a human decides here. Resolution is the decision
	// keyword (ok / wrong / wrong:<bid> / smear); a resolved row is excluded
	// from the next --export and skipped by a re-run --apply (idempotency).
	Resolution     string     `gorm:"not null;default:''" json:"resolution"`
	ResolutionNote string     `gorm:"not null;default:''" json:"resolution_note"`
	ResolvedAt     *time.Time `json:"resolved_at"`
}

func (BidIdentityVerdict) TableName() string { return "src_llm.bid_identity_verdict" }

// EnsureSchema creates the src_llm schema and migrates the suggestion tables.
func EnsureSchema(db *gorm.DB) error {
	if err := db.Exec(`CREATE SCHEMA IF NOT EXISTS src_llm`).Error; err != nil {
		return err
	}
	return db.AutoMigrate(&Run{}, &NamePairJudgment{}, &InfoboxExtraction{}, &BidIdentityVerdict{})
}

// hashInput is the resume key: a stable hex digest of the canonical input
// string for a task item.
func hashInput(parts ...string) string {
	h := sha256.New()
	for _, p := range parts {
		h.Write([]byte(p))
		h.Write([]byte{0})
	}
	return hex.EncodeToString(h.Sum(nil))
}
