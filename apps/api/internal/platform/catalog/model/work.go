// CatalogWorkIntro is one multilingual intro/description row for a BODYLESS
// work (site=” — no product database to hold its body), the media-aggregation
// pilot's first native media table (refs/proj/51 §3, step 52). It mirrors the
// catalog_work_title shape so the read face can merge it with the CLAIMED
// bridge (a claimed galgame_wiki work reads its intro directly from
// galgame.intro_* — a column→row pivot — and NEVER writes a row here:
// bridge-not-copy, §2). One row per (work, language, source): the unique key
// lets several sources coexist for the same language, and the read face merges
// them per language (source_id ascending wins).
//
// source_id is row-level provenance (§8.C) — NOT NULL with NO default: a
// meaningful source is always known at write time, and the default tag would
// drop a legitimately-low source id from the INSERT (the default-tag zero-value
// trap). shadow-never-delete (§8.B): a bodyless work later claimed keeps its
// rows (claim is reversible); the read face's strict XOR just stops reading
// them.
type CatalogWorkIntro struct {
	ID     int64 `gorm:"primaryKey;autoIncrement:false;type:bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY;default:(-)" json:"id"`
	WorkID int64 `gorm:"not null;uniqueIndex:uq_catalog_work_intro" json:"work_id"`
	// Lang is BCP-47 and part of the uniqueness key, hence NOT NULL DEFAULT ''
	// (same rationale as catalog_work_title / the alias tables).
	Lang string `gorm:"not null;default:'';uniqueIndex:uq_catalog_work_intro" json:"lang"`
	// Intro is the body text (verbatim from the source in this pilot — no
	// cleaning; §5). NOT NULL, no default: content is always supplied.
	Intro string `gorm:"type:text;not null" json:"intro"`
	// SourceID is the provenance FK (see the type doc). Part of the unique key.
	// A MACHINE-translated row (Provenance=1, step 75) carries the SOURCE row's
	// source_id — attribution is "translated from that source" — and is told
	// apart from the source row purely by Provenance, NOT by a distinct
	// source_id (so it never widens the unique key).
	SourceID int16 `gorm:"not null;uniqueIndex:uq_catalog_work_intro" json:"source_id"`
	// Provenance is 0=source (upstream original text) / 1=machine (LLM machine
	// translation — the step-75 ja→zh-Hans pilot). A meaningful zero value, so
	// the column is NOT NULL with NO default tag (the default-tag zero-value
	// trap): a source row records 0 EXPLICITLY on INSERT, never has the DB
	// default it. Machine rows NEVER masquerade as source data — the read face
	// prefers the source row for a language whenever both coexist.
	Provenance int16 `gorm:"not null" json:"provenance"`
	// SrcHash is sha256(source ja text) for a machine row — the re-translate
	// trigger: when the source text changes, its hash changes and the machine
	// row is re-translated (upsert). Empty on source rows. NOT NULL DEFAULT ''
	// (the lang/alias pattern: '' is the genuine not-applicable value here, safe
	// to default — unlike Provenance's meaningful 0).
	SrcHash string `gorm:"not null;default:''" json:"src_hash"`
	// MTModel is the model id that produced a machine row (accountability +
	// re-translate audit); empty on source rows. NOT NULL DEFAULT ''.
	MTModel   string    `gorm:"not null;default:''" json:"mt_model"`
	CreatedAt time.Time `json:"created_at"`
	UpdatedAt time.Time `json:"updated_at"`

	Work   *CatalogWork   `gorm:"foreignKey:WorkID" json:"work,omitempty"`
	Source *CatalogSource `gorm:"foreignKey:SourceID" json:"source,omitempty"`
}

func (CatalogWorkIntro) TableName() string { return "catalog_work_intro" }

// CatalogWorkCover is one cover image row for a BODYLESS work (site=” — no
// product database to hold its media), the media-aggregation wave's first
// byte-bearing native table (refs/proj/51 §3, step 53). It mirrors the
// galgame_cover shape (same columns, INDEPENDENT table — never the same row) so
// the read face can merge it with the CLAIMED bridge: a claimed galgame_wiki
// work reads its covers directly from galgame_cover (bridge-not-copy, §2) and
// NEVER writes a row here. One row per (work, image_hash): the unique key lets a
// work carry several covers, and the read face orders them by sort_order.
//
// Byte discipline (§4): a bodyless cover's bytes live in the CATALOG image
// scope (the same `catalog` image client the portrait wave opened) — distinct
// from galgame covers, which live in the galgame_wiki scope and are only ever
// bridge-READ here. shadow-never-delete (§8.B, the byte-version live wire): a
// bodyless work later claimed keeps its cover rows (claim is reversible); the
// read face's strict XOR stops reading them, but their bytes stay in catalog
// scope, so catalog-image-refping MUST keep pinging them (a missed shadowed row
// = GC eats a live image, the 66k-frozen failure class).
//
// source_id is row-level provenance (§8.C) — NOT NULL with NO default (the
// default-tag zero-value trap: a legitimately-low source id would drop from the
// INSERT). sexual/violence/sort_order default 0 (0 is their intended value AND
// zero, so the default tag is safe — no trap); kind allows the empty string
// (unknown / user upload), continuing galgame_cover semantics.
type CatalogWorkCover struct {
	ID     int64 `gorm:"primaryKey;autoIncrement:false;type:bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY;default:(-)" json:"id"`
	WorkID int64 `gorm:"not null;uniqueIndex:uq_catalog_work_cover" json:"work_id"`
	// ImageHash is the sha-256 the bytes are keyed by in the image service
	// (catalog scope). Part of the unique key.
	ImageHash string `gorm:"not null;uniqueIndex:uq_catalog_work_cover" json:"image_hash"`
	// SortOrder is the gallery/pin position (0 = pinned landscape banner,
	// mirroring galgame_cover). Meaningful zero == default zero → default tag safe.
	SortOrder int `gorm:"not null;default:0" json:"sort_order"`
	// Kind labels the cover type (VNDB-ish: main / pkgfront / dig / …); the empty
	// string is allowed (unknown / user upload), continuing galgame_cover semantics.
	Kind string `gorm:"not null;default:''" json:"kind"`
	// PortraitPinned marks the vertical PORTRAIT pin (the value kungal/moyu read
	// for the portrait-first UI). Mirrors galgame_cover.portrait_pinned.
	PortraitPinned bool `gorm:"not null;default:false" json:"portrait_pinned"`
	// Sexual/Violence are the per-image content-rating flags (0 = safe), matching
	// galgame_cover; 0 is both the intended default and the zero value (no trap).
	Sexual   int16 `gorm:"not null;default:0" json:"sexual"`
	Violence int16 `gorm:"not null;default:0" json:"violence"`
	// SourceID is the provenance FK (see the type doc). Part of no unique key —
	// several covers may share a source; the (work, image_hash) key is the identity.
	SourceID  int16     `gorm:"not null" json:"source_id"`
	CreatedAt time.Time `json:"created_at"`
	UpdatedAt time.Time `json:"updated_at"`

	Work   *CatalogWork   `gorm:"foreignKey:WorkID" json:"work,omitempty"`
	Source *CatalogSource `gorm:"foreignKey:SourceID" json:"source,omitempty"`
}

