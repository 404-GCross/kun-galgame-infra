// CatalogSeries is one work series (step 94, refs/proj/94 option B): a
// first-class grouping entity rather than O(n²) pairwise same_series edges —
// the series id/name from the source stays addressable (a future series page),
// membership is O(n), and future vndb/bgm series lanes append rows to the SAME
// table with their own source_id. Currently dlsite-sourced only (series_id
