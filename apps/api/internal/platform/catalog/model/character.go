package model

import (
	"time"

	"gorm.io/datatypes"
	"gorm.io/gorm"
)

// CatalogCharacter is a fictional character. Single layer + aliases
// (characters have no persona problem); the same character across media is
// ONE row — that is the point of the shared entity layer.
type CatalogCharacter struct {
	ID              int64   `gorm:"primaryKey;autoIncrement:false;type:bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY;default:(-)" json:"id"`
	DisplayName     string  `gorm:"not null" json:"display_name"`
	DisplayNameNorm string  `gorm:"->;-:migration" json:"display_name_norm"`
	Latin           *string `json:"latin"`
	Lang            string  `gorm:"not null;default:''" json:"lang"`
	// Gender uses the Gender* constants; NULL = unknown.
	Gender      *int16 `json:"gender"`
	Description string `gorm:"not null;default:''" json:"description"`
	// InstanceOf is the cross-universe variant escape hatch (doc 17 R6, VNDB
	// instance_of): a variant character points at its base character instead
	// of forcing duplicated rows or an over-merged one. Nullable self FK.
	InstanceOf *int64 `gorm:"index;type:bigint" json:"instance_of"`
	// ImageHash is the character portrait's content-addressed hash in the image
	// service (same shape as the galgame/work image columns); NULL until the
	// step-47 VNDB portrait wave backfills it. This step only lands the column.
	ImageHash *string `json:"image_hash"`
	// --- typical-set physical attributes (refs/proj/81 field PR C2) ---
	// The display-core attribute set that most sources carry, promoted to real
	// typed columns (the long tail lives in Extra). Every column is a nullable
	// pointer: NULL = unknown/unset (no meaningful zero, no default tag). Written
	// by internal/jobs/charattrs from the VNDB typed columns (survivorship: vndb
	// preferred) and the Bangumi infobox (bgm fills gaps). BirthdayMonth/Day are
	// month+day only — the year is not a real column (kept in Extra when a source
	// supplies one).
	BirthdayMonth *int16 `json:"birthday_month"`
	BirthdayDay   *int16 `json:"birthday_day"`
	// BloodType uses the BloodType* constants (1=A 2=B 3=AB 4=O); NULL = unknown.
	BloodType *int16 `json:"blood_type"`
	// HeightCm/WeightKg are the character's canonical height/weight; BustCm/
	// WaistCm/HipCm are the three-size measurements; all in cm/kg. Cup is the
	// bra-cup letter (verbatim source token, upper-cased: A/B/…/AAA).
	HeightCm *int16  `json:"height_cm"`
	WeightKg *int16  `json:"weight_kg"`
	BustCm   *int16  `json:"bust_cm"`
	WaistCm  *int16  `json:"waist_cm"`
	HipCm    *int16  `json:"hip_cm"`
	Cup      *string `json:"cup"`
	// Extra is the governed long-tail escape hatch (doc 17 R9 shape, cloned from
	// catalog_work): object-only jsonb, source-namespaced. charattrs writes the
	// Bangumi infobox long-tail under the "bgm" key ({"bgm": {"星座": "…", …}});
	// the namespace is replaced wholesale each run (idempotent). datatypes.JSON's
	// zero value is nil, so the default '{}' fires with no zero-value trap.
	Extra           datatypes.JSON `gorm:"type:jsonb;not null;default:'{}'" json:"extra"`
	FieldProvenance datatypes.JSON `gorm:"type:jsonb;not null;default:'{}'" json:"field_provenance"`
	CreatedAt       time.Time      `json:"created_at"`
	UpdatedAt       time.Time      `json:"updated_at"`
	DeletedAt       gorm.DeletedAt `gorm:"index" json:"-"`

	Instance *CatalogCharacter `gorm:"foreignKey:InstanceOf" json:"instance,omitempty"`
}

func (CatalogCharacter) TableName() string { return "catalog_character" }

// CatalogCharacterAlias mirrors CatalogNameAlias for characters.
type CatalogCharacterAlias struct {
	ID          int64   `gorm:"primaryKey;autoIncrement:false;type:bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY;default:(-)" json:"id"`
	CharacterID int64   `gorm:"not null;type:bigint;uniqueIndex:uq_catalog_character_alias_owner_name_lang" json:"character_id"`
	Name        string  `gorm:"not null;uniqueIndex:uq_catalog_character_alias_owner_name_lang" json:"name"`
	NameNorm    string  `gorm:"->;-:migration" json:"name_norm"`
	Latin       *string `json:"latin"`
	Lang        string  `gorm:"not null;default:'';uniqueIndex:uq_catalog_character_alias_owner_name_lang" json:"lang"`
	// Kind uses the AliasKind* constants.
	Kind               int16 `gorm:"not null" json:"kind"`
	IsPrimaryForLocale bool  `gorm:"not null" json:"is_primary_for_locale"`

	Character *CatalogCharacter `gorm:"foreignKey:CharacterID" json:"character,omitempty"`
}

func (CatalogCharacterAlias) TableName() string { return "catalog_character_alias" }

// CatalogCharacterIntro is one multilingual intro/description row for a
// character (field PR C1, refs/proj/65), cloning the catalog_work_intro shape.
// Characters are catalog-NATIVE entities — no claimed/bodyless split, no XOR,
// no bridging: every row here is read directly by the character read face. One
// row per (character, language, source): the unique key lets several sources
// coexist for the same language, and the read face merges them per language
// (source_id ascending wins), exactly like the work intro merge.
//
// source_id is row-level provenance — NOT NULL with NO default: a meaningful
// source is always known at write time, and a default tag would drop a
// legitimately-low source id from the INSERT (the default-tag zero-value trap).
type CatalogCharacterIntro struct {
	ID          int64 `gorm:"primaryKey;autoIncrement:false;type:bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY;default:(-)" json:"id"`
	CharacterID int64 `gorm:"not null;uniqueIndex:uq_catalog_character_intro" json:"character_id"`
	// Lang is BCP-47 and part of the uniqueness key, hence NOT NULL DEFAULT ''
	// (same rationale as catalog_work_intro / the alias tables).
	Lang string `gorm:"not null;default:'';uniqueIndex:uq_catalog_character_intro" json:"lang"`
	// Intro is the body text — verbatim from the source except CRLF→LF and,
	// for VNDB, the spoiler-span removal + markup unwrap (see
	// internal/jobs/entityintros). NOT NULL, no default: content is always
	// supplied.
	Intro string `gorm:"type:text;not null" json:"intro"`
	// SourceID is the provenance FK. Part of the unique key.
	SourceID  int16     `gorm:"not null;uniqueIndex:uq_catalog_character_intro" json:"source_id"`
	CreatedAt time.Time `json:"created_at"`
	UpdatedAt time.Time `json:"updated_at"`

	Character *CatalogCharacter `gorm:"foreignKey:CharacterID" json:"character,omitempty"`
	Source    *CatalogSource    `gorm:"foreignKey:SourceID" json:"source,omitempty"`
}

func (CatalogCharacterIntro) TableName() string { return "catalog_character_intro" }
