// CatalogCharacterIntro is one multilingual intro/description row for a
// character (field PR C1, refs/proj/65), cloning the catalog_work_intro shape.
// Characters are catalog-NATIVE entities — no claimed/bodyless split, no XOR,
// no bridging: every row here is read directly by the character read face. One
// row per (character, language, source): the unique key lets several sources
// coexist for the same language, and the read face merges them per language
// (source_id ascending wins), exactly like the work intro merge.
//
// source_id is row-level provenance — NOT NULL with NO default: a meaningful
// source is always known at write time, and a default tag would drop a
// legitimately-low source id from the INSERT (the default-tag zero-value trap).
type CatalogCharacterIntro struct {
	ID          int64 `gorm:"primaryKey;autoIncrement:false;type:bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY;default:(-)" json:"id"`
	CharacterID int64 `gorm:"not null;uniqueIndex:uq_catalog_character_intro" json:"character_id"`
	// Lang is BCP-47 and part of the uniqueness key, hence NOT NULL DEFAULT ''
	// (same rationale as catalog_work_intro / the alias tables).
	Lang string `gorm:"not null;default:'';uniqueIndex:uq_catalog_character_intro" json:"lang"`
	// Intro is the body text — verbatim from the source except CRLF→LF and,
	// for VNDB, the spoiler-span removal + markup unwrap (see
	// internal/jobs/entityintros). NOT NULL, no default: content is always
	// supplied.
	Intro string `gorm:"type:text;not null" json:"intro"`
	// SourceID is the provenance FK. Part of the unique key. A MACHINE-translated
	// row (Provenance=1) carries the SOURCE row's source_id — attribution is
	// "translated from that source" — and is told apart from the source row
	// purely by Provenance (the catalog_work_intro step-75 shape).
	SourceID int16 `gorm:"not null;uniqueIndex:uq_catalog_character_intro" json:"source_id"`
	// Provenance is 0=source / 1=machine (entity intro MT, refs/proj/172). A
	// meaningful zero value, so NOT NULL with NO default tag (the default-tag
	// zero-value trap); a source row records 0 explicitly on INSERT.
	Provenance int16 `gorm:"not null" json:"provenance"`
	// SrcHash is sha256(source text) on a machine row — the re-translate
	// trigger. Empty on source rows; NOT NULL DEFAULT ''.
	SrcHash string `gorm:"not null;default:''" json:"src_hash"`
	// MTModel is the model id that produced a machine row; empty on source rows.
	MTModel   string    `gorm:"not null;default:''" json:"mt_model"`
	CreatedAt time.Time `json:"created_at"`
	UpdatedAt time.Time `json:"updated_at"`

	Character *CatalogCharacter `gorm:"foreignKey:CharacterID" json:"character,omitempty"`
	Source    *CatalogSource    `gorm:"foreignKey:SourceID" json:"source,omitempty"`
}

func (CatalogCharacterIntro) TableName() string { return "catalog_character_intro" }

// CatalogCharacterTrait is one VNDB trait vocabulary row (step 93, refs/proj/93
// ruling 1): a SINGLE-SOURCE vocabulary, so vndb_tid IS the source map — no
// separate map table until a second source exists (catalog_tag grew one because
// it converges THREE sources; YAGNI here). Names/descriptions land verbatim EN
// this wave; alias/description are the future zh-localization feedstock.
// GroupTID is the verbatim VNDB root-group tid (” = this row IS a root group);
// group display names resolve by self-join at read time. Sexual marks the two
// sexual trait families (685/3,327) — stored, surfaced on the read face, gated
// by consumers (the step-81 BWH/cup precedent: the catalog is R18-capable).
type CatalogCharacterTrait struct {
	ID int64 `gorm:"primaryKey;autoIncrement:false;type:bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY;default:(-)" json:"id"`
	// VndbTID is the VNDB trait id ("i1"), UNIQUE — the single-source map.
	VndbTID string `gorm:"column:vndb_tid;not null;uniqueIndex:uq_catalog_character_trait_vndb_tid" json:"vndb_tid"`
	// Name is the verbatim VNDB English trait name.
	Name string `gorm:"not null" json:"name"`
	// NameZh is the Simplified-Chinese rendering of Name (wave 176). '' = none
	// yet, which is the honest state for a trait nobody has rendered — the read
	// faces omit the field rather than echoing the English twice. A DEFAULT ''
	// is correct here (unlike the intro-table provenance columns): every
	// pre-existing row genuinely has no Chinese name, so AutoMigrate's
	// `ADD COLUMN … NOT NULL DEFAULT ''` writes the right value and no
	// preMigrate backfill block is needed.
	NameZh string `gorm:"column:name_zh;not null;default:''" json:"name_zh"`
	// NameZhProvenance records WHERE NameZh came from: 0 = curated (the MIT
	// community dictionary / a human), 1 = machine translation. Meaningful only
	// when NameZh != '' — an empty name has no provenance — which is why a
	// plain default:0 carries no zero-value trap: the '' rows the default lands
	// on are exactly the rows whose provenance nobody reads. Curated beats
	// machine: the ingest path may overwrite a 1 but never a 0.
	NameZhProvenance int16 `gorm:"column:name_zh_provenance;not null;default:0" json:"name_zh_provenance"`
	// GroupTID is the verbatim VNDB root-group tid; '' = this row is a root.
	// NOT NULL with no default: the importer always writes it explicitly ('' is
	// a meaningful value — the default-tag zero-value trap avoided).
	GroupTID string `gorm:"column:group_tid;not null" json:"group_tid"`
	// GOrder is VNDB's display order within the group.
	GOrder int16 `gorm:"column:gorder;not null" json:"gorder"`
	// DefaultSpoil is VNDB's default spoiler level for NEW taggings (0/1/2) —
	// vocabulary metadata; the per-character level lives on the link row.
	DefaultSpoil int16 `gorm:"column:default_spoil;not null" json:"default_spoil"`
	Sexual       bool  `gorm:"not null" json:"sexual"`
	Searchable   bool  `gorm:"not null" json:"searchable"`
	// Applicable=false means VNDB stopped offering the trait for new taggings;
	// existing links are real history and are stored regardless (ruling 5).
	Applicable bool `gorm:"not null" json:"applicable"`
	// Alias is the newline-separated VNDB alias list (search feedstock).
	Alias string `gorm:"type:text;not null" json:"alias"`
	// Description is the VNDB English description, BBCode-ish (zh feedstock).
	Description string    `gorm:"type:text;not null" json:"description"`
	CreatedAt   time.Time `json:"created_at"`
	UpdatedAt   time.Time `json:"updated_at"`
}

func (CatalogCharacterTrait) TableName() string { return "catalog_character_trait" }

// CatalogCharacterTraitParent is one DAG edge of the trait hierarchy (VNDB
