// CatalogCharacterTraitLink is one character×trait assignment (VNDB
// chars_traits via the exact character anchors, ~2.9M rows). SpoilerLevel is
// the per-character 0/1/2 (the read face defaults to 0, ?spoilers widens); Lie
// is VNDB's "presented as true, actually false" flag, surfaced verbatim.
// UNIQUE (character_id, trait_id) — character_id is the index prefix, so
// per-character reads need no extra single-column index. Writes are batched
// multi-row upserts with change detection (spoiler re-grades upstream →
// refresh-runnable, the step-62 discipline).
type CatalogCharacterTraitLink struct {
	ID          int64 `gorm:"primaryKey;autoIncrement:false;type:bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY;default:(-)" json:"id"`
	CharacterID int64 `gorm:"not null;uniqueIndex:uq_catalog_character_trait_link,priority:1" json:"character_id"`
	TraitID     int64 `gorm:"not null;uniqueIndex:uq_catalog_character_trait_link,priority:2" json:"trait_id"`
	// SpoilerLevel is the per-character spoiler grade (0 none / 1 minor /
	// 2 major). NOT NULL, no default — 0 is meaningful and always written.
	SpoilerLevel int16 `gorm:"not null" json:"spoiler_level"`
	// Lie: the trait is presented as true but is actually a lie (VNDB flag).
	Lie       bool      `gorm:"not null" json:"lie"`
	CreatedAt time.Time `json:"created_at"`
	UpdatedAt time.Time `json:"updated_at"`

	Character *CatalogCharacter      `gorm:"foreignKey:CharacterID" json:"character,omitempty"`
	Trait     *CatalogCharacterTrait `gorm:"foreignKey:TraitID" json:"trait,omitempty"`
}

func (CatalogCharacterTraitLink) TableName() string { return "catalog_character_trait_link" }
